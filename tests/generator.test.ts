import { mkdtemp, readFile, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { describe, expect, it } from "vitest"
import { type DmmfDatamodel, emitModels } from "../src/adapters/prisma/generator/emit.js"
import { handleLine } from "../src/adapters/prisma/generator/rpc.js"

// The DMMF `prisma generate` hands a generator for prisma/schema.prisma (trimmed to what is read).
const datamodel: DmmfDatamodel = {
  enums: [],
  models: [
    {
      name: "User",
      primaryKey: null,
      uniqueFields: [],
      fields: [
        {
          name: "id",
          kind: "scalar",
          type: "Int",
          isList: false,
          isRequired: true,
          isId: true,
          isUnique: false,
          hasDefaultValue: true,
        },
        {
          name: "email",
          kind: "scalar",
          type: "String",
          isList: false,
          isRequired: true,
          isId: false,
          isUnique: true,
          hasDefaultValue: false,
        },
        { name: "posts", kind: "object", type: "Post", isList: true, isRequired: true },
      ],
    },
    {
      name: "Like",
      primaryKey: null,
      uniqueFields: [["userId", "postId"]],
      fields: [
        { name: "userId", kind: "scalar", type: "Int", isRequired: true },
        { name: "postId", kind: "scalar", type: "Int", isRequired: true },
      ],
    },
  ],
}

describe("emitModels", () => {
  it("emits one descriptor per model: create shape, primary key, unique constraints", () => {
    expect(
      emitModels(datamodel),
    ).toBe(`// Generated by zod-bridge from the Prisma schema. Do not edit: rerun \`prisma generate\`.
import { z } from "zod"
import { defineModel } from "zod-bridge/prisma"

export const UserModel = defineModel({
  name: "User",
  shape: {
    id: z.int().optional(),
    email: z.string(),
  },
  primaryKey: ["id"],
  unique: [["email"]],
})

export const LikeModel = defineModel({
  name: "Like",
  shape: {
    userId: z.int(),
    postId: z.int(),
  },
  primaryKey: [],
  unique: [["userId", "postId"]],
})
`)
  })

  it("matches the committed descriptors of the test schema (npm run generate:models)", async () => {
    const committed = await readFile(new URL("./generated/zod-bridge.ts", import.meta.url), "utf8")
    const emitted = emitModels(datamodel, { importPath: "../../src/adapters/prisma/index.js" })
    const [header = "", user = "", like = ""] = emitted.split("\n\n")
    expect(committed.startsWith(`${header}\n\n${user}\n\n`)).toBe(true)
    expect(committed.endsWith(`\n\n${like}`)).toBe(true)
  })

  it("maps every scalar, enums, lists, nullable and defaulted fields; skips relations and Unsupported", () => {
    const source = emitModels({
      enums: [{ name: "Role", values: [{ name: "USER" }, { name: "ADMIN" }] }],
      models: [
        {
          name: "Account",
          primaryKey: { fields: ["tenantId", "slug"] },
          uniqueFields: [["tenantId", "email"]],
          fields: [
            { name: "tenantId", kind: "scalar", type: "Int", isRequired: true },
            { name: "slug", kind: "scalar", type: "String", isRequired: true },
            {
              name: "email",
              kind: "scalar",
              type: "String",
              isRequired: true,
              dbName: "email_address",
            },
            { name: "role", kind: "enum", type: "Role", isRequired: true, hasDefaultValue: true },
            { name: "bio", kind: "scalar", type: "String", isRequired: false },
            { name: "tags", kind: "scalar", type: "String", isList: true, isRequired: true },
            { name: "balance", kind: "scalar", type: "Decimal", isRequired: true },
            { name: "views", kind: "scalar", type: "BigInt", isRequired: true },
            { name: "score", kind: "scalar", type: "Float", isRequired: true },
            { name: "active", kind: "scalar", type: "Boolean", isRequired: true },
            {
              name: "createdAt",
              kind: "scalar",
              type: "DateTime",
              isRequired: true,
              hasDefaultValue: true,
            },
            {
              name: "updatedAt",
              kind: "scalar",
              type: "DateTime",
              isRequired: true,
              isUpdatedAt: true,
            },
            { name: "settings", kind: "scalar", type: "Json", isRequired: true },
            { name: "avatar", kind: "scalar", type: "Bytes", isRequired: true },
            {
              name: "location",
              kind: "unsupported",
              type: "geometry",
              isRequired: true,
              isUnique: true,
            },
            { name: "owner", kind: "object", type: "User", isRequired: true },
          ],
        },
      ],
    })

    expect(source).toContain(`  shape: {
    tenantId: z.int(),
    slug: z.string(),
    email: z.string(),
    role: z.enum(["USER", "ADMIN"]).optional(),
    bio: z.string().nullish(),
    tags: z.array(z.string()).optional(),
    balance: z.union([z.number(), z.string()]),
    views: z.bigint(),
    score: z.number(),
    active: z.boolean(),
    createdAt: z.date().optional(),
    updatedAt: z.date().optional(),
    settings: z.json(),
    avatar: z.instanceof(Uint8Array),
  },
  primaryKey: ["tenantId", "slug"],
  unique: [["tenantId", "email"]],
  columns: {
    email: "email_address",
  },
})`)
  })

  it("drops a key or constraint that names a field without a column schema", () => {
    const source = emitModels({
      models: [
        {
          name: "Place",
          primaryKey: { fields: ["location"] },
          uniqueFields: [["name", "location"]],
          fields: [
            { name: "name", kind: "scalar", type: "String", isRequired: true },
            { name: "location", kind: "unsupported", type: "geometry", isRequired: true },
          ],
        },
      ],
    })
    expect(source).toContain("  primaryKey: [],\n  unique: [],\n")
  })
})

describe("generator protocol", () => {
  it("answers getManifest with the default output", async () => {
    const line = await handleLine(JSON.stringify({ jsonrpc: "2.0", id: 1, method: "getManifest" }))
    expect(JSON.parse(line!)).toEqual({
      jsonrpc: "2.0",
      id: 1,
      result: {
        manifest: { prettyName: "zod-bridge models", defaultOutput: "./generated/zod-bridge.ts" },
      },
    })
  })

  it("generate writes the module to the output path, creating directories", async () => {
    const dir = await mkdtemp(join(tmpdir(), "zod-bridge-"))
    try {
      const output = join(dir, "nested", "models.ts")
      const line = await handleLine(
        JSON.stringify({
          jsonrpc: "2.0",
          id: 2,
          method: "generate",
          params: {
            generator: { output: { value: output }, config: { importPath: "../bridge.js" } },
            dmmf: { datamodel },
          },
        }),
      )
      expect(JSON.parse(line!)).toEqual({ jsonrpc: "2.0", id: 2, result: null })
      expect(await readFile(output, "utf8")).toBe(
        emitModels(datamodel, { importPath: "../bridge.js" }),
      )
    } finally {
      await rm(dir, { recursive: true })
    }
  })

  it("reports a non-.ts output as an error that names the fix", async () => {
    const line = await handleLine(
      JSON.stringify({
        jsonrpc: "2.0",
        id: 3,
        method: "generate",
        params: { generator: { output: { value: "/tmp/out-dir" } }, dmmf: { datamodel } },
      }),
    )
    const response = JSON.parse(line!) as { error: { message: string } }
    expect(response.error.message).toContain("output must be a .ts file path")
    expect(response.error.message).toContain("Fix:")
  })

  it("ignores lines that are not requests", async () => {
    expect(await handleLine("not json")).toBeUndefined()
    expect(await handleLine(JSON.stringify({ jsonrpc: "2.0", method: "notify" }))).toBeUndefined()
  })
})
